-- 12. VISTAS
CREATE OR REPLACE VIEW vista_pedido_total AS
SELECT
    p.id_pedido,
    COALESCE(SUM(dp.cantidad * dp.precio_unitario), 0)::NUMERIC(12,2) AS total
FROM pedido p
LEFT JOIN detalle_pedido dp ON dp.id_pedido = p.id_pedido
GROUP BY p.id_pedido;

CREATE OR REPLACE VIEW vista_carrito_total AS
SELECT
    c.id_carrito,
    COALESCE(SUM(vpt.total), 0)::NUMERIC(12,2) AS total
FROM carrito c
LEFT JOIN pedido p ON p.id_carrito = c.id_carrito
LEFT JOIN vista_pedido_total vpt ON vpt.id_pedido = p.id_pedido
GROUP BY c.id_carrito;

CREATE OR REPLACE VIEW vista_factura_total AS
SELECT
    f.id_factura,
    p.monto AS total
FROM factura f
JOIN pago p ON p.id_pago = f.id_pago;

CREATE OR REPLACE VIEW vista_producto_categoria AS
SELECT p.id_producto, p.nombre, c.nombre AS categoria, p.precio,
       CASE WHEN i.estado = 'ACTIVO' THEN i.cantidad ELSE 0 END AS stock,
       p.estado, p.imagen_url, p.precio_oferta, p.id_categoria
FROM producto p
JOIN categoria c ON c.id_categoria = p.id_categoria
LEFT JOIN inventario i ON i.id_producto = p.id_producto;

CREATE OR REPLACE VIEW vista_ingresos_producto_categoria AS
SELECT
    c.id_categoria,
    c.nombre AS categoria,
    pr.id_producto,
    pr.nombre AS producto,
    SUM(dp.cantidad) AS unidades_vendidas,
    SUM(dp.cantidad * dp.precio_unitario)::NUMERIC(14,2) AS ingresos
FROM detalle_pedido dp
JOIN pedido pe ON pe.id_pedido = dp.id_pedido
JOIN producto pr ON pr.id_producto = dp.id_producto
JOIN categoria c ON c.id_categoria = pr.id_categoria
WHERE pe.estado IN ('CONFIRMADO', 'PAGADO', 'ENVIADO', 'ENTREGADO')
GROUP BY c.id_categoria, c.nombre, pr.id_producto, pr.nombre;

