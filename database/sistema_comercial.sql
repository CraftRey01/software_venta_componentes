-- 14. SINCRONIZAR SECUENCIAS IDENTITY
DO $$
DECLARE
    registro RECORD;
    ultimo_id BIGINT;
BEGIN
    FOR registro IN
        SELECT table_schema, table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = 'comercial'
          AND is_identity = 'YES'
    LOOP
        EXECUTE format('SELECT MAX(%I) FROM %I.%I',
                       registro.column_name, registro.table_schema, registro.table_name)
        INTO ultimo_id;
        IF ultimo_id IS NOT NULL THEN
            PERFORM setval(
                pg_get_serial_sequence(registro.table_schema || '.' || registro.table_name,
                                       registro.column_name),
                ultimo_id, true);
        END IF;
    END LOOP;
END $$;

COMMIT;
