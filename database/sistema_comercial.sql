BEGIN;

CREATE SCHEMA IF NOT EXISTS comercial;
SET search_path TO comercial, public;

-- 1. CATALOGO E INVENTARIO
CREATE TABLE IF NOT EXISTS categoria (
    id_categoria INTEGER PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL,
    descripcion  TEXT,
    estado       VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_categoria_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS producto (
    id_producto   INTEGER PRIMARY KEY,
    id_categoria  INTEGER NOT NULL,
    nombre        VARCHAR(150) NOT NULL,
    precio        NUMERIC(12,2) NOT NULL DEFAULT 0,
    precio_oferta NUMERIC(12,2),
    descripcion   TEXT,
    marca         VARCHAR(100),
    imagen_url    VARCHAR(255),
    estado        VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT fk_producto_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria),
    CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    CONSTRAINT ck_producto_precio_oferta
        CHECK (precio_oferta IS NULL OR (precio_oferta >= 0 AND precio_oferta < precio)),
    CONSTRAINT ck_producto_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS inventario (
    id_inventario INTEGER PRIMARY KEY,
    id_producto   INTEGER NOT NULL UNIQUE,
    cantidad      INTEGER NOT NULL DEFAULT 0,
    fecha_ingreso DATE,
    ubicacion     VARCHAR(150),
    estado        VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT fk_inventario_producto
        FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
    CONSTRAINT ck_inventario_cantidad CHECK (cantidad >= 0),
    CONSTRAINT ck_inventario_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

-- 2. CLIENTES, DIRECCIONES, CORREOS Y EQUIPOS
CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL,
    telefono   VARCHAR(30),
    estado     VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_cliente_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS direccion_cliente (
    id_direccion INTEGER PRIMARY KEY,
    id_cliente   INTEGER NOT NULL,
    direccion    VARCHAR(255) NOT NULL,
    CONSTRAINT fk_direccion_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
        ON DELETE CASCADE,
    CONSTRAINT uq_direccion_cliente UNIQUE (id_cliente, direccion)
);

CREATE TABLE IF NOT EXISTS email_cliente (
    id_email   INTEGER PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    email      VARCHAR(254) NOT NULL UNIQUE,
    CONSTRAINT fk_email_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS equipo_cliente (
    id_equipo     INTEGER PRIMARY KEY,
    id_cliente    INTEGER NOT NULL,
    marca         VARCHAR(100) NOT NULL,
    modelo        VARCHAR(100),
    serie         VARCHAR(120) UNIQUE,
    estado        VARCHAR(40) NOT NULL DEFAULT 'REGISTRADO',
    fecha_compra  DATE,
    observaciones TEXT,
    CONSTRAINT fk_equipo_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
);

-- 3. VENDEDORES Y USUARIOS
CREATE TABLE IF NOT EXISTS vendedor (
    id_vendedor        INTEGER PRIMARY KEY,
    nombre             VARCHAR(100) NOT NULL,
    apellido           VARCHAR(100) NOT NULL,
    ci                 VARCHAR(30) UNIQUE,
    telefono           VARCHAR(30),
    email              VARCHAR(254) UNIQUE,
    estado             VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
    fecha_contratacion DATE,
    CONSTRAINT ck_vendedor_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS usuario_sistema (
    id_usuario    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario       VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol           VARCHAR(20) NOT NULL,
    id_cliente    INTEGER,
    id_vendedor   INTEGER,
    activo        BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_usuario_sistema_cliente
        FOREIGN KEY (id_cliente) REFERENCES comercial.cliente (id_cliente),
    CONSTRAINT fk_usuario_sistema_vendedor
        FOREIGN KEY (id_vendedor) REFERENCES comercial.vendedor (id_vendedor),
    CONSTRAINT ck_usuario_sistema_rol
        CHECK (rol IN ('CLIENTE', 'VENDEDOR', 'ADMINISTRADOR')),
    CONSTRAINT ck_usuario_sistema_relacion
        CHECK (
            (rol = 'CLIENTE' AND id_cliente IS NOT NULL AND id_vendedor IS NULL)
            OR (rol = 'VENDEDOR' AND id_cliente IS NULL AND id_vendedor IS NOT NULL)
            OR (rol = 'ADMINISTRADOR' AND id_cliente IS NULL AND id_vendedor IS NULL)
        )
);

-- 4. CARRITO, PEDIDO Y DETALLE
CREATE TABLE IF NOT EXISTS carrito (
    id_carrito     INTEGER PRIMARY KEY,
    id_cliente     INTEGER NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado         VARCHAR(20) NOT NULL DEFAULT 'ABIERTO',
    observaciones  TEXT,
    CONSTRAINT fk_carrito_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    CONSTRAINT ck_carrito_estado
        CHECK (estado IN ('ABIERTO', 'PENDIENTE', 'CONVERTIDO', 'CANCELADO'))
);

CREATE TABLE IF NOT EXISTS pedido (
    id_pedido     INTEGER PRIMARY KEY,
    id_carrito    INTEGER NOT NULL,
    id_vendedor   INTEGER NOT NULL,
    fecha         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado        VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    observaciones TEXT,
    canal         VARCHAR(50),
    CONSTRAINT fk_pedido_carrito
        FOREIGN KEY (id_carrito) REFERENCES carrito(id_carrito),
    CONSTRAINT fk_pedido_vendedor
        FOREIGN KEY (id_vendedor) REFERENCES vendedor(id_vendedor),
    CONSTRAINT ck_pedido_estado
        CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'PAGADO',
                          'ENVIADO', 'ENTREGADO', 'CANCELADO'))
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
    id_pedido       INTEGER NOT NULL,
    id_producto     INTEGER NOT NULL,
    cantidad        INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_detalle_pedido PRIMARY KEY (id_pedido, id_producto),
    CONSTRAINT fk_detalle_pedido_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido)
        ON DELETE CASCADE,
    CONSTRAINT fk_detalle_pedido_producto
        FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
    CONSTRAINT ck_detalle_pedido_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_pedido_precio CHECK (precio_unitario >= 0)
);

-- 5. PAGO, FACTURA Y ENVIO
-- La FK de pago.id_orden se agrega en la seccion 6, cuando existe orden_servicio.
CREATE TABLE IF NOT EXISTS pago (
    id_pago   INTEGER PRIMARY KEY,
    id_pedido INTEGER UNIQUE,
    id_orden  INTEGER,
    monto     NUMERIC(12,2) NOT NULL,
    metodo    VARCHAR(50) NOT NULL,
    fecha     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado    VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT fk_pago_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido),
    CONSTRAINT ck_pago_monto CHECK (monto >= 0),
    CONSTRAINT ck_pago_estado
        CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO')),
    CONSTRAINT ck_pago_referencia
        CHECK (num_nonnulls(id_pedido, id_orden) = 1)
);

CREATE TABLE IF NOT EXISTS factura (
    id_factura INTEGER PRIMARY KEY,
    id_pago    INTEGER NOT NULL UNIQUE,
    fecha      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    serie      VARCHAR(30) NOT NULL,
    estado     VARCHAR(20) NOT NULL DEFAULT 'EMITIDA',
    CONSTRAINT fk_factura_pago
        FOREIGN KEY (id_pago) REFERENCES pago(id_pago),
    CONSTRAINT ck_factura_estado
        CHECK (estado IN ('EMITIDA', 'ANULADA'))
);

CREATE TABLE IF NOT EXISTS envio (
    id_envio   INTEGER PRIMARY KEY,
    id_factura INTEGER NOT NULL,
    fecha      TIMESTAMP WITH TIME ZONE,
    destino    VARCHAR(255) NOT NULL,
    pais       VARCHAR(100),
    costo      NUMERIC(12,2),
    estado     VARCHAR(40) NOT NULL DEFAULT 'PENDIENTE',
    empresa    VARCHAR(100),
    modalidad  VARCHAR(20) NOT NULL DEFAULT 'PUNTO_ENTREGA',
    CONSTRAINT fk_envio_factura
        FOREIGN KEY (id_factura) REFERENCES factura(id_factura),
    CONSTRAINT ck_envio_modalidad
        CHECK (modalidad IN ('RECOGIDA', 'PUNTO_ENTREGA'))
);

-- 6. SOPORTE TECNICO Y REPARACIONES
CREATE TABLE IF NOT EXISTS orden_servicio (
    id_orden            INTEGER PRIMARY KEY,
    id_cliente          INTEGER,
    tipo_equipo         VARCHAR(20),
    marca_equipo        VARCHAR(100),
    modelo_equipo       VARCHAR(100),
    serie_equipo        VARCHAR(120),
    fecha               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cita          TIMESTAMP WITH TIME ZONE,
    estado              VARCHAR(30) NOT NULL DEFAULT 'RECIBIDA',
    metodo_pago         VARCHAR(30),
    descripcion         TEXT,
    diagnostico         TEXT,
    tecnico             VARCHAR(150),
    id_usuario_tecnico  INTEGER,
    observaciones       TEXT,
    CONSTRAINT fk_orden_servicio_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
    CONSTRAINT fk_orden_servicio_usuario_tecnico
        FOREIGN KEY (id_usuario_tecnico) REFERENCES usuario_sistema(id_usuario),
    CONSTRAINT ck_orden_servicio_estado
        CHECK (estado IN ('RECIBIDA', 'EN_REVISION', 'EN_REPARACION',
                          'FINALIZADA', 'ENTREGADA', 'CANCELADA'))
);

ALTER TABLE pago
    ADD CONSTRAINT fk_pago_orden_servicio
    FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden);

-- Relacion N:N entre equipos y ordenes de servicio.
CREATE TABLE IF NOT EXISTS detalle_orden_equipo (
    id_orden  INTEGER NOT NULL,
    id_equipo INTEGER NOT NULL,
    CONSTRAINT pk_detalle_orden_equipo PRIMARY KEY (id_orden, id_equipo),
    CONSTRAINT fk_doe_orden
        FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden)
        ON DELETE CASCADE,
    CONSTRAINT fk_doe_equipo
        FOREIGN KEY (id_equipo) REFERENCES equipo_cliente(id_equipo)
);

-- Relacion 1:1: una orden de servicio tiene como maximo una reparacion.
CREATE TABLE IF NOT EXISTS reparacion (
    id_reparacion INTEGER PRIMARY KEY,
    id_orden      INTEGER NOT NULL UNIQUE,
    fecha_inicio  DATE,
    fecha_fin     DATE,
    descripcion   TEXT,
    estado        VARCHAR(40) NOT NULL DEFAULT 'PENDIENTE',
    costo         NUMERIC(12,2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_reparacion_orden
        FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden),
    CONSTRAINT ck_reparacion_costo CHECK (costo >= 0),
    CONSTRAINT ck_reparacion_fechas
        CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS pieza_utilizada (
    id_pieza INTEGER PRIMARY KEY,
    nombre   VARCHAR(150) NOT NULL,
    costo    NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado   VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT ck_pieza_costo CHECK (costo >= 0),
    CONSTRAINT ck_pieza_estado CHECK (estado IN ('ACTIVA', 'INACTIVA'))
);

-- Relacion N:N entre reparacion y pieza utilizada.
CREATE TABLE IF NOT EXISTS detalle_reparacion (
    id_reparacion INTEGER NOT NULL,
    id_pieza      INTEGER NOT NULL,
    cantidad      INTEGER NOT NULL,
    observaciones TEXT,
    CONSTRAINT pk_detalle_reparacion PRIMARY KEY (id_reparacion, id_pieza),
    CONSTRAINT fk_dr_reparacion
        FOREIGN KEY (id_reparacion) REFERENCES reparacion(id_reparacion)
        ON DELETE CASCADE,
    CONSTRAINT fk_dr_pieza
        FOREIGN KEY (id_pieza) REFERENCES pieza_utilizada(id_pieza),
    CONSTRAINT ck_dr_cantidad CHECK (cantidad > 0)
);

-- 7. HISTORIAL E HISTORIAL_VENDEDOR
CREATE TABLE IF NOT EXISTS historial (
    id_historial     INTEGER PRIMARY KEY,
    id_pedido        INTEGER,
    id_orden         INTEGER,
    id_usuario_evento INTEGER,
    fecha_evento     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_evento      VARCHAR(80) NOT NULL,
    descripcion      TEXT,
    observaciones    TEXT,
    CONSTRAINT fk_historial_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido),
    CONSTRAINT fk_historial_orden
        FOREIGN KEY (id_orden) REFERENCES orden_servicio(id_orden),
    CONSTRAINT fk_historial_usuario_evento
        FOREIGN KEY (id_usuario_evento) REFERENCES usuario_sistema(id_usuario),
    -- Cada evento pertenece a un pedido o a una orden de servicio, pero no a ambos.
    CONSTRAINT ck_historial_referencia
        CHECK (num_nonnulls(id_pedido, id_orden) = 1)
);

-- Relacion N:N entre vendedores e historial.
CREATE TABLE IF NOT EXISTS historial_vendedor (
    id_vendedor  INTEGER NOT NULL,
    id_historial INTEGER NOT NULL,
    CONSTRAINT pk_historial_vendedor PRIMARY KEY (id_vendedor, id_historial),
    CONSTRAINT fk_hv_vendedor
        FOREIGN KEY (id_vendedor) REFERENCES vendedor(id_vendedor)
        ON DELETE CASCADE,
    CONSTRAINT fk_hv_historial
        FOREIGN KEY (id_historial) REFERENCES historial(id_historial)
        ON DELETE CASCADE
);

-- 8. REPORTES
CREATE TABLE IF NOT EXISTS reporte (
    id_reporte       INTEGER PRIMARY KEY,
    tipo_reporte     VARCHAR(100) NOT NULL,
    fecha_generacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    periodo_inicio   DATE,
    periodo_fin      DATE,
    formato          VARCHAR(30),
    estado           VARCHAR(30) NOT NULL DEFAULT 'GENERADO',
    CONSTRAINT ck_reporte_periodo
        CHECK (periodo_fin IS NULL OR periodo_inicio IS NULL
               OR periodo_fin >= periodo_inicio)
);

-- Un reporte agrupa pedidos; un pedido puede figurar en varios reportes.
CREATE TABLE IF NOT EXISTS detalle_reporte (
    id_reporte INTEGER NOT NULL,
    id_pedido  INTEGER NOT NULL,
    CONSTRAINT pk_detalle_reporte PRIMARY KEY (id_reporte, id_pedido),
    CONSTRAINT fk_detalle_reporte_reporte
        FOREIGN KEY (id_reporte) REFERENCES reporte(id_reporte)
        ON DELETE CASCADE,
    CONSTRAINT fk_detalle_reporte_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido)
        ON DELETE CASCADE
);

-- 9. RESERVAS TEMPORALES DEL CARRITO EN LINEA
CREATE TABLE IF NOT EXISTS reserva_carrito (
    token       VARCHAR(32) NOT NULL,
    id_cliente  INTEGER NOT NULL REFERENCES comercial.cliente(id_cliente),
