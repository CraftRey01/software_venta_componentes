    cantidad    INTEGER NOT NULL CHECK (cantidad > 0),
    reservado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vence_en    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT reserva_carrito_pkey PRIMARY KEY (token, id_producto)
);

